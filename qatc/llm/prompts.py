def game_context_block(game_name: str, llm_context: str) -> str:
    """게임별 배경 지식. 세션 내내 고정이므로 캐시 접두사에 들어간다."""
    if not llm_context:
        return f"대상 게임: {game_name}"
    return f"대상 게임: {game_name}\n\n{llm_context}"
